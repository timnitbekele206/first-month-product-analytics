"""Join the three CSVs into one row per user and write data/users.js.

Run from the project folder:  python3 scripts/build_data.py
The dashboard loads data/users.js, so no server-side code is needed.
"""
import csv
import json
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"


def read(name):
    with open(DATA / name, newline="") as f:
        return {r["User_ID"]: r for r in csv.DictReader(f)}


def flag(value):
    """'1' -> 1, '0' -> 0, blank -> None (unknown; never treated as 0)."""
    return None if value == "" else int(float(value))


customers = read("customers.csv")
features = read("feature_adoption.csv")
funnel = read("funnel_sessions.csv")

users = []
for uid, c in customers.items():
    f, s = features[uid], funnel[uid]
    users.append(
        {
            "id": uid,
            "device": c["Device_Type"],
            "region": c["Region"],
            "referral": c["Referral_Source"],
            "subscribed": flag(c["Subscription_Status"]),
            "feature": f["Feature_Name"],
            "used": flag(f["Feature_Used"]),
            "day1": flag(f["Retention_Day_1"]),
            "day7": flag(f["Retention_Day_7"]),
            "day30": flag(f["Retention_Day_30"]),
            "s1": flag(s["Step_1_Visited"]),
            "s2": flag(s["Step_2_Clicked"]),
            "s3": flag(s["Step_3_Submitted"]),
            "s4": flag(s["Step_4_Confirmed"]),
            "completed": flag(s["Completion"]),
        }
    )

out = DATA / "users.js"
out.write_text("// Generated by scripts/build_data.py - do not edit by hand\nwindow.USERS = " + json.dumps(users, separators=(",", ":")) + ";\n")
print(f"Wrote {len(users)} users to {out}")
